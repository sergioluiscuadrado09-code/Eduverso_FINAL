/* Icono que representa a cada categoría del catálogo */
const ICONO_POR_CATEGORIA = {
  "Tecnología": "codigo",
  "Idiomas": "idioma",
  "Arte y Diseño": "paleta",
  "Negocios": "maletin",
  "Ciencias": "matraz",
  "Desarrollo Personal": "usuario"
};

/* Devuelve el SVG de un curso; si el icono guardado no existe
   (por ejemplo, datos antiguos), usa el de su categoría. */
function obtenerIconoCurso(curso) {
  if (ICONOS[curso.icono]) return ICONOS[curso.icono];
  const porCategoria = ICONO_POR_CATEGORIA[curso.categoria];
  return ICONOS[porCategoria] || ICONOS.libro;
}

/* Rellena los <span data-icono="..."> del HTML */
document.querySelectorAll("[data-icono]").forEach(elemento => {
  const svg = ICONOS[elemento.dataset.icono];
  if (svg) elemento.innerHTML = svg;
});
